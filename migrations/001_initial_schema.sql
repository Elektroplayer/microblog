-- ТАБЛИЦЫ

CREATE TABLE users (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	username TEXT not null UNIQUE,
	display_name text,
	password_hash TEXT NOT null,
	created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE posts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT NOT NULL unique,
    is_hidden bool not null default false,
    title TEXT not null,
    description TEXT,
    author TEXT not null,
    content TEXT not null,
    content_hash TEXT NOT null,
    created_at TIMESTAMPTZ not null default NOW(),
    updated_at TIMESTAMPTZ
);

CREATE TABLE comments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id INTEGER NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
    user_id INTEGER REFERENCES users(id) ON DELETE set null, -- если null, значит автор удалён
    content TEXT, -- если я его решил удалить
    response_to INTEGER REFERENCES comments(id) ON DELETE SET NULL, -- ответ на другой комментарий, на будущее
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ
);

CREATE TABLE sessions (
    id TEXT PRIMARY KEY, -- TODO: в будущем это тоже стоит хешировать
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL
);

-- ТРИГГЕРЫ

-- Обновлять update после обновления статьи

CREATE OR REPLACE FUNCTION update_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS posts_updated_at ON posts;

CREATE TRIGGER posts_updated_at
BEFORE UPDATE OF content ON posts
FOR EACH ROW
WHEN (OLD.content IS DISTINCT FROM NEW.content)
EXECUTE FUNCTION update_updated_at();


-- Изменять хэш после обновления
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE FUNCTION update_post_metadata()
RETURNS TRIGGER AS $$
BEGIN
    NEW.content_hash = encode(digest(NEW.content, 'sha256'), 'hex');
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS posts_metadata ON posts;

CREATE TRIGGER posts_metadata
BEFORE INSERT OR update OF content ON posts
FOR EACH row
EXECUTE FUNCTION update_post_metadata();

-- ИНДЕКСЫ

CREATE INDEX sessions_user_id_idx ON sessions(user_id);
CREATE INDEX sessions_expires_at_idx ON sessions(expires_at);

CREATE INDEX comments_post_id_idx ON comments (post_id);
CREATE INDEX comments_response_to_idx ON comments (response_to);

CREATE INDEX posts_visible_created_at_id_idx
ON posts (created_at DESC, id DESC)
WHERE is_hidden = false;


